const tidy = (s: string) => s.toLowerCase().replace(/[֑-ׇً-ْ]/g, '').replace(/[^\p{L}\p{N}\s"״]/gu, ' ').replace(/\s+/g, ' ').trim();

/**
 * The answers that fit what the customer typed, best first. A longer
 * matching phrase counts for more than a short word; nothing is returned
 * when no key matches, so the bot never guesses.
 */
export function matchFaq(input: string): FaqItem[] {
  const text = ' ' + tidy(input) + ' ';
  if (text.trim().length < 2) return [];
  const scored = FAQ.map((item) => {
    let score = 0;
    for (const k of item.keys) {
      const key = tidy(k);
      // A whole phrase says more than a word, and a long word more than a short one.
      if (key && text.includes(key)) score += key.includes(' ') ? 5 : key.length >= 5 ? 3 : 2;
    }
    return { item, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, 3).map((x) => x.item);
}
