/** Returns the docs with the same-numbered sections replaced ("3. ..." replaces the section whose heading starts with "3."). */
export function withSiteOrdering(docs: Record<LegalSlug, LegalDoc>, lang: 'he' | 'ar'): Record<LegalSlug, LegalDoc> {
  const patch = lang === 'he' ? HE : AR;
  const out = { ...docs };
  for (const slug of Object.keys(patch) as LegalSlug[]) {
    const byNumber = patch[slug]!;
    out[slug] = { ...docs[slug], sections: docs[slug].sections.map((s) => byNumber[parseInt(s.h, 10)] ?? s) };
  }
  return out;
}
