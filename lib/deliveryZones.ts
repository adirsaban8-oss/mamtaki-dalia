/** Strip quotes, geresh, hyphens and spaces so "ג'סר א-זרקא" ≈ "גסר אזרקא". */
export function normalizePlace(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/[׳'"״`\---.,()]/g, '')
    .replace(/\s+/g, '')
    .replace(/^ال/, '');
}

export type PlaceMatch =
  | { kind: 'served'; zone: Zone; place: [string, string] }
  | { kind: 'south'; place: [string, string] }
  | { kind: 'unknown' };

export function findPlace(query: string): PlaceMatch {
  const q = normalizePlace(query);
  if (q.length < 2) return { kind: 'unknown' };
  const hit = (p: [string, string]) =>
    p.some((name) => {
      const n = normalizePlace(name);
      return n === q || (q.length >= 3 && (n.startsWith(q) || q.startsWith(n)));
    });
  for (const zone of zones) {
    const place = zone.places.find(hit);
    if (place) return { kind: 'served', zone, place };
  }
  const south = notServed.find(hit);
  if (south) return { kind: 'south', place: south };
  return { kind: 'unknown' };
}
